"""Convert the two existing Fluent SVG paths to rotatable Slint path geometry.

Software 1.18 cannot transform images. Rotate the original Bézier control points
instead; this preserves the icon contours without adding a bitmap cache or crate.
"""
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path


def path_commands(data):
    tokens = re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", data)
    output = []
    x = y = 0.0
    index = 0
    while index < len(tokens):
        command = tokens[index]
        index += 1
        count = {"M": 2, "L": 2, "C": 6, "H": 1, "V": 1, "Z": 0}.get(command)
        if count is None:
            raise ValueError(f"Unexpected SVG command {command}; inspect the changed source icon")
        values = tokens[index:index + count]
        index += count
        if command == "Z":
            output.append("Close { }")
            continue
        if command == "H":
            values = [values[0], str(y)]
            command = "L"
        elif command == "V":
            values = [str(x), values[0]]
            command = "L"
        x, y = map(float, values[-2:])
        pairs = list(zip(values[::2], values[1::2]))
        fields = []
        prefixes = ["control-1-", "control-2-", ""] if command == "C" else [""]
        for prefix, (px, py) in zip(prefixes, pairs):
            fields += [f"{prefix}x: root.rx({px}, {py});", f"{prefix}y: root.ry({px}, {py});"]
        output.append({"M": "MoveTo", "L": "LineTo", "C": "CubicTo"}[command] + " { " + " ".join(fields) + " }")
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    parts = ["""// Generated by scripts/generate-rust-rotating-icons.py from the existing
// Microsoft Fluent UI System Icons paths (MIT; assets/fluent/LICENSE.txt).
// Explicit point rotation also works on Software, which cannot transform images.
export component RotatingGlyph inherits Rectangle {
    in property <string> icon-key;
    in property <angle> angle;
    in property <color> tint;
    private property <float> center: root.icon-key == "refresh" ? 10 : 12;
    private property <float> cosine: cos(root.angle);
    private property <float> sine: sin(root.angle);
    function rx(x: float, y: float) -> float { return root.center + (x - root.center) * root.cosine - (y - root.center) * root.sine; }
    function ry(x: float, y: float) -> float { return root.center + (x - root.center) * root.sine + (y - root.center) * root.cosine; }
"""]
    for name, file, size in (("refresh", "ic_fluent_arrow_clockwise_20_regular.svg", 20), ("settings", "ic_fluent_settings_24_regular.svg", 24)):
        svg = ET.parse(root / "ui/assets/fluent" / file).getroot()
        parts.append(f'    if root.icon-key == "{name}": Path {{\n        width: parent.width; height: parent.height; viewbox-width: {size}; viewbox-height: {size}; fill: root.tint;\n')
        for path in svg.findall("{http://www.w3.org/2000/svg}path"):
            parts.extend("        " + command + "\n" for command in path_commands(path.attrib["d"]))
        parts.append("    }\n")
    parts.append("}\n")
    text = "".join(parts)
    destination = root / "ui/rotating-icons.slint"
    if args.check:
        if destination.read_text(encoding="utf-8") != text:
            raise ValueError("Rotating icon paths differ from their source SVGs; regenerate and review")
    else:
        destination.write_text(text, encoding="utf-8")
    print("Fluent rotating paths match the source SVGs." if args.check else "Generated Fluent rotating paths.")


if __name__ == "__main__":
    main()
