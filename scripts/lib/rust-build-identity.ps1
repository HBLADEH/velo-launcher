function Get-VeloWorkspaceIdentity {
    param([string]$Repository)
    $commit = & git -C $Repository rev-parse --verify HEAD
    if ($LASTEXITCODE -ne 0 -or -not $commit) { throw 'Cannot read the current source commit.' }
    $status = & git -C $Repository status --porcelain=v1 --untracked-files=all --ignore-submodules=none
    if ($LASTEXITCODE -ne 0) { throw 'Cannot determine whether the source worktree is clean.' }
    [pscustomobject]@{ Commit = $commit; Dirty = [bool]$status }
}

function Get-VeloRustSources {
    param([string]$Repository)
    $names = @('Cargo.toml', 'Cargo.lock', 'rust-toolchain.toml', 'windows-toolchain.json', 'build.rs', 'LICENSE')
    $files = @(foreach ($name in $names) { Get-Item -LiteralPath (Join-Path $Repository $name) -Force })
    foreach ($name in '.cargo', 'src', 'ui', 'examples', 'tests', 'windows', 'licenses', 'scripts') {
        $root = Get-Item -LiteralPath (Join-Path $Repository $name) -Force
        if (-not $root.PSIsContainer -or $root.Attributes.HasFlag([IO.FileAttributes]::ReparsePoint)) {
            throw "Invalid source input directory: $name"
        }
        $files += @(Get-ChildItem -LiteralPath $root.FullName -Recurse -Force)
    }
    foreach ($file in $files | Sort-Object FullName) {
        $path = [IO.Path]::GetRelativePath($Repository, $file.FullName).Replace('\', '/')
        if ($file.Attributes.HasFlag([IO.FileAttributes]::ReparsePoint)) { throw "Invalid linked source input: $path" }
        # Python bytecode generated by the tooling is not a maintained input.
        if ($file.PSIsContainer -or $path -match '^scripts/(?:.*/)?__pycache__/') { continue }
        [ordered]@{ Path = $path; SHA256 = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash }
    }
}

function Assert-VeloRustSources {
    param([string]$Repository, [object[]]$Recorded)
    $remaining = [Collections.Generic.Dictionary[string,string]]::new([StringComparer]::Ordinal)
    foreach ($source in $Recorded) {
        if (-not $source.Path -or -not $remaining.TryAdd($source.Path, $source.SHA256)) {
            throw 'Verification must list each source input exactly once.'
        }
    }
    foreach ($source in Get-VeloRustSources -Repository $Repository) {
        if (-not $remaining.ContainsKey($source.Path)) { throw "Source added after verification: $($source.Path)" }
        if ($remaining[$source.Path] -ne $source.SHA256) { throw "Source changed after verification: $($source.Path)" }
        [void]$remaining.Remove($source.Path)
    }
    if ($remaining.Count) { throw "Source removed after verification: $($remaining.Keys -join ', ')" }
}

function Read-VeloVerifiedBuild {
    param([string]$Repository, [string]$Renderer, [string]$ArtifactDirectory, [switch]$Product, [switch]$Release)
    if (-not $ArtifactDirectory) {
        $group = if ($Product) { 'product-artifacts' } else { 'artifacts' }
        $ArtifactDirectory = Join-Path $Repository "target/$group/$Renderer"
    }
    $directory = (Resolve-Path -LiteralPath $ArtifactDirectory).Path
    $identityPath = Join-Path $directory 'build-identity.json'
    $verificationPath = Join-Path $directory 'verification.json'
    $metadataPath = Join-Path $directory 'cargo-metadata.json'
    $executable = Join-Path $directory 'velo-slint.exe'
    $identity = Get-Content -LiteralPath $identityPath -Raw | ConvertFrom-Json
    $receipt = Get-Content -LiteralPath $verificationPath -Raw | ConvertFrom-Json
    if ($identity.ProductIdentity -ne $Product.IsPresent -or $receipt.ProductIdentity -ne $Product.IsPresent) {
        throw 'Product and preview verification receipts cannot be interchanged.'
    }
    if ($receipt.ChecksPassed -isnot [bool] -or -not $receipt.ChecksPassed -or
        $receipt.SmokeTestPassed -isnot [bool] -or -not $receipt.SmokeTestPassed -or
        $receipt.Renderer -ne $Renderer -or $identity.Renderer -ne $Renderer -or
        $identity.Target -ne 'x86_64-pc-windows-msvc' -or
        (Get-FileHash -LiteralPath $executable).Hash -ne $receipt.ExecutableSHA256 -or
        $identity.ExecutableSHA256 -ne $receipt.ExecutableSHA256 -or
        (Get-FileHash -LiteralPath $identityPath).Hash -ne $receipt.BuildIdentitySHA256 -or
        (Get-FileHash -LiteralPath $metadataPath).Hash -ne $receipt.CargoMetadataSHA256) {
        throw "Packaging $Renderer requires a matching successful full verification with -SmokeTest."
    }
    if ($Release) {
        $workspace = Get-VeloWorkspaceIdentity -Repository $Repository
        if ($workspace.Dirty) { throw 'Public packaging requires a clean current worktree.' }
        if ($identity.WorkspaceDirty -isnot [bool] -or $identity.WorkspaceDirty -or $identity.WorkspaceCommit -ne $workspace.Commit) {
            throw "The $Renderer release receipt must bind the current clean source commit; verify again."
        }
    }
    Assert-VeloRustSources -Repository $Repository -Recorded $identity.Sources
    [pscustomobject]@{
        Receipt = $receipt; IdentityPath = $identityPath; VerificationPath = $verificationPath
        MetadataPath = $metadataPath; Executable = $executable
    }
}
